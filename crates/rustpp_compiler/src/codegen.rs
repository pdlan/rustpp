use crate::diagnostic::Diagnostic;
use crate::hir::{Constructor, LifecycleStep, Module, OwnerKind, TypeKind, TypeRef};
use crate::metadata::stable_class_id;

pub fn emit(abi_identity: &str, module: &Module) -> Result<String, Vec<Diagnostic>> {
    validate_backend_plans(module)?;
    let mut output = String::new();
    output.push_str("// @generated by rustpp; do not edit.\n");
    output.push_str(&format!(
        "// ABI identity: {}\n\n",
        abi_identity.replace('\n', " ")
    ));

    for class in &module.value_classes {
        output.push_str(&format!(
            "#[allow(dead_code)]\npub struct {}{} {} {{\n",
            class.name, class.generics.declaration, class.generics.where_clause
        ));
        for field in &class.fields {
            if field.public {
                output.push_str("pub ");
            }
            output.push_str(&format!(
                "{}: {},\n",
                field.name,
                backend_type(module, &field.ty)
            ));
        }
        output.push_str("}\n");
        output.push_str(&format!(
            "impl{} {}{} {} {{\n",
            class.generics.impl_params,
            class.name,
            class.generics.type_args,
            class.generics.where_clause
        ));
        output.push_str("pub fn new(");
        for (index, param) in class.constructor.params.iter().enumerate() {
            if index > 0 {
                output.push_str(", ");
            }
            output.push_str(&format!(
                "{}: {}",
                param.name,
                backend_type(module, &param.ty)
            ));
        }
        output.push_str(") -> Self { Self {\n");
        for initializer in &class.constructor.initializers {
            output.push_str(&initializer.field);
            if let Some(expression) = &initializer.expression {
                output.push_str(": ");
                output.push_str(expression);
            }
            output.push_str(",\n");
        }
        output.push_str("} }\n");
        for method in &class.methods {
            if method.public {
                output.push_str("pub ");
            }
            output.push_str(&backend_method_signature(module, &method.signature));
            output.push_str(" {\n");
            output.push_str(method.body.as_deref().unwrap_or_default());
            output.push_str("\n}\n");
        }
        output.push_str("}\n");
        if let Some(body) = &class.drop_body {
            output.push_str(&format!(
                "impl{} Drop for {}{} {} {{ fn drop(&mut self) {{\n{body}\n}} }}\n",
                class.generics.impl_params,
                class.name,
                class.generics.type_args,
                class.generics.where_clause
            ));
        }
    }

    if !module.classes.is_empty() {
        output.push_str(
            "#[doc(hidden)] #[derive(Clone, Copy, PartialEq, Eq)] pub struct __RppClassId(pub u128);\n\
             #[doc(hidden)] pub struct __RppCastEntry {\n\
             target: __RppClassId,\n\
             make_const: unsafe fn(*const (), *mut ()),\n\
             make_mut: unsafe fn(*mut (), *mut ()),\n\
             }\n\
             #[doc(hidden)] pub struct __RppTypeDesc {\n\
             active_class: __RppClassId,\n\
             complete_storage_class: __RppClassId,\n\
             casts: &'static [__RppCastEntry],\n\
             }\n\
             impl __RppTypeDesc {\n\
             fn find(&self, target: __RppClassId) -> Option<&__RppCastEntry> { self.casts.iter().find(|entry| entry.target == target) }\n\
             #[doc(hidden)] pub fn active_class_id(&self) -> u128 { self.active_class.0 }\n\
             #[doc(hidden)] pub fn complete_storage_class_id(&self) -> u128 { self.complete_storage_class.0 }\n\
             }\n\
             mod __rpp_runtime_object_sealed { pub trait Sealed {} }\n\
             pub trait RustppObject: __rpp_runtime_object_sealed::Sealed {\n\
             #[doc(hidden)] fn __rpp_complete_address(&self) -> usize;\n\
             #[doc(hidden)] fn __rpp_type_desc(&self) -> &'static __RppTypeDesc;\n\
             }\n",
        );
    }

    for class in &module.classes {
        let data = format!("__{}Data", class.name);
        let storage = format!("__{}Storage", class.name);
        let frame = format!("__{}ActivationFrame", class.name);
        let activation_guard = format!("__{}ActivationGuard", class.name);
        let deactivation_guard = format!("__{}DeactivationGuard", class.name);
        let view = format!("{}View", class.name);
        let box_owner = format!("{}Box", class.name);
        let rc_owner = format!("{}Rc", class.name);
        let arc_owner = format!("{}Arc", class.name);
        let seal_module = format!("__rpp_{}_sealed", class.name.to_lowercase());
        let inline_initializers: Vec<_> = class
            .constructor
            .initializers
            .iter()
            .filter(|initializer| initializer.inline.is_some())
            .collect();
        let has_subobjects = !class.bases.is_empty() || !inline_initializers.is_empty();

        output.push_str(&format!("struct {frame} {{\n"));
        for base in &class.bases {
            let base_class = class_by_id(module, base.class);
            output.push_str(&format!(
                "{}: __{}ActivationFrame,\n",
                base_frame_field(base.class),
                base_class.name
            ));
        }
        for initializer in class
            .constructor
            .initializers
            .iter()
            .filter(|initializer| initializer.inline.is_some())
        {
            let inline = initializer.inline.as_ref().unwrap();
            let child = class_by_id(module, inline.class);
            output.push_str(&format!(
                "__rpp_{}: __{}ActivationFrame,\n",
                initializer.field, child.name
            ));
        }
        for param in &class.activation_params {
            output.push_str(&format!(
                "{}: {},\n",
                param.name,
                backend_type(module, &param.ty)
            ));
        }
        output.push_str("}\n");
        output.push_str(&format!("#[allow(dead_code)]\nstruct {data} {{\n"));
        for field in class.fields.iter().rev() {
            output.push_str(&format!(
                "{}: {},\n",
                field.name,
                backend_type(module, &field.ty)
            ));
        }
        for base in class.bases.iter().rev() {
            let base_class = class_by_id(module, base.class);
            output.push_str(&format!(
                "{}: __{}Data,\n",
                base_data_field(base.class),
                base_class.name
            ));
        }
        output.push_str("}\n");
        if has_subobjects {
            output.push_str(&format!(
                "struct {activation_guard} {{ data: *mut {data}, completed: usize }}\n"
            ));
            output.push_str(&format!("impl Drop for {activation_guard} {{ fn drop(&mut self) {{\n// SAFETY [SC-STAGE-VIEW]: rollback owns the unique final Data borrow and only deactivates successfully completed substages.\nunsafe {{\n"));
            let mut stage_index = class.bases.len() + inline_initializers.len();
            for initializer in inline_initializers.iter().rev() {
                stage_index -= 1;
                output.push_str(&format!(
                    "if self.completed > {stage_index} {{ (*self.data).{}.__rpp_deinit(); }}\n",
                    initializer.field
                ));
            }
            for base in class.bases.iter().rev() {
                stage_index -= 1;
                output.push_str(&format!(
                    "if self.completed > {stage_index} {{ (*self.data).{}.__rpp_deinit(); }}\n",
                    base_data_field(base.class)
                ));
            }
            output.push_str("} } }\n");
            output.push_str(&format!(
                "struct {deactivation_guard} {{ data: *mut {data}, remaining: usize }}\n"
            ));
            output.push_str(&format!("impl Drop for {deactivation_guard} {{ fn drop(&mut self) {{\n// SAFETY [SC-STAGE-VIEW]: unwind cleanup owns the unique complete Data borrow and consumes each remaining deactivation obligation once.\nunsafe {{\n"));
            let mut stage_index = class.bases.len() + inline_initializers.len();
            for initializer in inline_initializers.iter().rev() {
                stage_index -= 1;
                output.push_str(&format!(
                    "if self.remaining > {stage_index} {{ self.remaining = {stage_index}; (*self.data).{}.__rpp_deinit(); }}\n",
                    initializer.field
                ));
            }
            for base in class.bases.iter().rev() {
                stage_index -= 1;
                output.push_str(&format!(
                    "if self.remaining > {stage_index} {{ self.remaining = {stage_index}; (*self.data).{}.__rpp_deinit(); }}\n",
                    base_data_field(base.class)
                ));
            }
            output.push_str("} } }\n");
        }
        output.push_str(&format!("impl {data} {{\n"));
        output.push_str("fn __rpp_new(");
        emit_params(&mut output, module, &class.constructor);
        output.push_str(&format!(") -> (Self, {frame}) {{\n"));
        for base in &class.bases {
            let base_class = class_by_id(module, base.class);
            let initializer = class
                .constructor
                .base_initializers
                .iter()
                .find(|initializer| initializer.class == base.class)
                .expect("validated direct base must have one initializer");
            output.push_str(&format!(
                "let ({}_data, {}_frame) = __{}Data::__rpp_new({});\n",
                base_data_field(base.class),
                base_frame_field(base.class),
                base_class.name,
                initializer.arguments
            ));
        }
        for initializer in &class.constructor.initializers {
            if let Some(inline) = &initializer.inline {
                let child = class_by_id(module, inline.class);
                output.push_str(&format!(
                    "let (__rpp_{}_data, __rpp_{}_frame) = __{}Data::__rpp_new({});\n",
                    initializer.field, initializer.field, child.name, inline.arguments
                ));
            } else {
                let expression = initializer
                    .expression
                    .as_deref()
                    .unwrap_or(&initializer.field);
                output.push_str(&format!(
                    "let __rpp_{}_value = {};\n",
                    initializer.field, expression
                ));
            }
        }
        output.push_str("let data = Self {\n");
        for initializer in &class.constructor.initializers {
            let suffix = if initializer.inline.is_some() {
                "data"
            } else {
                "value"
            };
            output.push_str(&format!(
                "{}: __rpp_{}_{suffix},\n",
                initializer.field, initializer.field
            ));
        }
        for base in &class.bases {
            output.push_str(&format!(
                "{}: {}_data,\n",
                base_data_field(base.class),
                base_data_field(base.class)
            ));
        }
        output.push_str(&format!("}};\nlet frame = {frame} {{\n"));
        for base in &class.bases {
            output.push_str(&format!(
                "{}: {}_frame,\n",
                base_frame_field(base.class),
                base_frame_field(base.class)
            ));
        }
        for initializer in &inline_initializers {
            output.push_str(&format!(
                "__rpp_{}: __rpp_{}_frame,\n",
                initializer.field, initializer.field
            ));
        }
        for param in &class.activation_params {
            output.push_str(&format!("{},\n", param.name));
        }
        output.push_str("};\n(data, frame)\n}\n");
        output.push_str(&format!(
            "#[allow(unreachable_code)]\nfn __rpp_init(&mut self, frame: {frame}) {{\n"
        ));
        if class.activation_params.is_empty() && !has_subobjects {
            output.push_str("let _ = frame;\n");
        } else {
            output.push_str(&format!("let {frame} {{ "));
            for base in &class.bases {
                let field = base_frame_field(base.class);
                output.push_str(&format!("{field}: {field}_value,"));
            }
            for initializer in &inline_initializers {
                output.push_str(&format!(
                    "__rpp_{}: __rpp_{}_frame,",
                    initializer.field, initializer.field
                ));
            }
            for param in &class.activation_params {
                output.push_str(&format!("{},", param.name));
            }
            output.push_str(" } = frame;\n");
        }
        if has_subobjects {
            output.push_str(&format!(
                "// SAFETY [SC-STAGE-VIEW]: the guard points to this uniquely borrowed final Data only for this activation call.\nlet mut guard = {activation_guard} {{ data: self as *mut _, completed: 0 }};\n"
            ));
            for base in &class.bases {
                let data_field = base_data_field(base.class);
                let frame_field = base_frame_field(base.class);
                output.push_str(&format!(
                    "self.{data_field}.__rpp_init({frame_field}_value);\nguard.completed += 1;\n"
                ));
            }
            for initializer in &inline_initializers {
                output.push_str(&format!(
                    "self.{}.__rpp_init(__rpp_{}_frame);\nguard.completed += 1;\n",
                    initializer.field, initializer.field
                ));
            }
        }
        if class.abstract_ {
            output.push_str(&class.init_body);
        } else {
            output.push_str(&format!(
                "// SAFETY [SC-STAGE-VIEW, SC-DATA-STORAGE-LAYOUT]: the helper preserves this unique Data borrow's lifetime in the transparent current-class stage view.\nlet stage = unsafe {{ __rpp_borrow_stage_{}(self) }};\nlet _ = &stage;\n",
                class.id.0
            ));
            output.push_str(&rewrite_lifecycle_body(module, class, &class.init_body));
        }
        if has_subobjects {
            output.push_str("\nguard.completed = 0;\n");
        }
        output.push_str(
            "\n}\n#[allow(unreachable_code, unused_mut, unused_variables)]\nfn __rpp_deinit(&mut self) {\n",
        );
        if has_subobjects {
            output.push_str(&format!(
                "// SAFETY [SC-STAGE-VIEW]: the guard owns all remaining deactivation obligations for this uniquely borrowed Data during unwinding.\nlet mut guard = {deactivation_guard} {{ data: self as *mut _, remaining: {} }};\n",
                class.bases.len() + inline_initializers.len()
            ));
        }
        if class.abstract_ {
            output.push_str(&class.deinit_body);
        } else {
            output.push_str(&format!(
                "// SAFETY [SC-STAGE-VIEW, SC-DATA-STORAGE-LAYOUT]: the helper preserves this unique Data borrow's lifetime in the transparent current-class stage view.\nlet stage = unsafe {{ __rpp_borrow_stage_{}(self) }};\nlet _ = &stage;\n",
                class.id.0
            ));
            output.push_str(&rewrite_lifecycle_body(module, class, &class.deinit_body));
        }
        for initializer in inline_initializers.iter().rev() {
            output.push_str(&format!(
                "\nguard.remaining -= 1;\nself.{}.__rpp_deinit();\n",
                initializer.field
            ));
        }
        for base in class.bases.iter().rev() {
            output.push_str(&format!(
                "\nguard.remaining -= 1;\nself.{}.__rpp_deinit();\n",
                base_data_field(base.class)
            ));
        }
        if has_subobjects {
            output.push_str("\nguard.remaining = 0;\n");
        }
        output.push_str("\n}\n");
        output.push_str("}\n");
        if let Some(body) = &class.drop_body {
            output.push_str(&format!("impl Drop for {data} {{ fn drop(&mut self) {{\n"));
            output.push_str(body);
            output.push_str("\n} }\n");
        }

        output.push_str(&format!(
            "#[allow(dead_code)]\n#[repr(transparent)]\nstruct {storage}({data});\n"
        ));
        let storage_deinit = if class.abstract_ {
            "__rpp_deinit"
        } else {
            "__rpp_deinit_complete"
        };
        output.push_str(&format!(
            "impl Drop for {storage} {{ fn drop(&mut self) {{ self.0.{storage_deinit}(); }} }}\n"
        ));
        if !class.abstract_ {
            let direct_guard = format!("__RppDirectGuard{}", class.id.0);
            let structural_guard = format!("__RppDirectStructuralGuard{}", class.id.0);
            output.push_str(&format!(
                "struct {structural_guard} {{ data: *mut {data} }}\n\
                 impl Drop for {structural_guard} {{ fn drop(&mut self) {{\n\
                 // SAFETY [SC-ACTIVATION-COMMIT]: the direct-place guard uniquely owns initialized Data in compiler-created MaybeUninit storage.\n\
                 unsafe {{ std::ptr::drop_in_place(self.data); }}\n\
                 }} }}\n\
                 struct {direct_guard} {{ data: *mut {data}, live: bool }}\n\
                 impl Drop for {direct_guard} {{ fn drop(&mut self) {{\n\
                 let structural = {structural_guard} {{ data: self.data }};\n\
                 if self.live {{\n\
                 // SAFETY [SC-STAGE-VIEW]: a live direct-place guard uniquely owns the complete object and consumes its deactivation obligation once.\n\
                 unsafe {{ (*self.data).__rpp_deinit_complete(); }}\n\
                 }}\n\
                 drop(structural);\n\
                 }} }}\n"
            ));
        }
        output.push_str(&format!("mod {seal_module} {{ pub trait Sealed {{}} }}\n"));
        let public_bases: Vec<_> = class
            .bases
            .iter()
            .filter(|base| base.visibility == crate::hir::BaseVisibility::Public)
            .map(|base| class_by_id(module, base.class))
            .collect();
        let has_private_interface = class.methods.iter().any(|method| {
            !method.public
                && (matches!(method.kind, crate::hir::MethodKind::NonVirtual)
                    || method.slot == Some(method.id))
        });
        if has_private_interface {
            output.push_str("#[allow(private_bounds)]\n");
        }
        output.push_str(&format!("pub trait {view}: RustppObject"));
        for base in &public_bases {
            output.push_str(&format!(" + {}View", base.name));
        }
        if has_private_interface {
            output.push_str(&format!(" + __{}Internal", class.name));
        }
        output.push_str(&format!(" + {seal_module}::Sealed {{\n"));
        for method in class.methods.iter().filter(|method| {
            method.public
                && (matches!(method.kind, crate::hir::MethodKind::NonVirtual)
                    || method.slot == Some(method.id))
        }) {
            output.push_str(&backend_trait_method_signature(module, &method.signature));
            output.push_str(";\n");
        }
        output.push_str("}\n");
        let internal_trait = format!("__{}Internal", class.name);
        let private_methods: Vec<_> = class
            .methods
            .iter()
            .filter(|method| {
                !method.public
                    && (matches!(method.kind, crate::hir::MethodKind::NonVirtual)
                        || method.slot == Some(method.id))
            })
            .collect();
        if !private_methods.is_empty() {
            output.push_str(&format!("trait {internal_trait} {{\n"));
            for method in &private_methods {
                output.push_str(&backend_trait_method_signature(module, &method.signature));
                output.push_str(";\n");
            }
            output.push_str("}\n");
        }
        if !class.abstract_ {
            emit_type_descriptor(&mut output, abi_identity, module, class, &storage);
            let stage = stage_name(class.id);
            for target in class_view_closure(module, class.id) {
                emit_shared_view_method_macro(&mut output, module, class.id, target);
                emit_shared_internal_method_macro(&mut output, module, class.id, target);
            }
            output.push_str(&format!(
                "#[allow(dead_code)] #[repr(transparent)] struct {stage}({data});\n\
                 unsafe fn __rpp_borrow_stage_{}(data: &mut {data}) -> &mut {stage} {{\n\
                 // SAFETY [SC-STAGE-VIEW, SC-DATA-STORAGE-LAYOUT]: transparent stage layout matches Data and the output lifetime is tied to the input borrow.\n\
                 unsafe {{ &mut *(data as *mut {data}).cast::<{stage}>() }}\n\
                 }}\n\
                 impl __rpp_runtime_object_sealed::Sealed for {stage} {{}}\n\
                 impl RustppObject for {stage} {{\n\
                 fn __rpp_complete_address(&self) -> usize {{ self as *const Self as usize }}\n\
                 fn __rpp_type_desc(&self) -> &'static __RppTypeDesc {{ &{} }}\n\
                 }}\n",
                class.id.0,
                type_descriptor_name(class.id)
            ));
            for target in class_view_closure(module, class.id) {
                let target_seal = format!("__rpp_{}_sealed", target.name.to_lowercase());
                output.push_str(&format!(
                    "impl {target_seal}::Sealed for {stage} {{}}\nimpl {}View for {stage} {{\n",
                    target.name
                ));
                output.push_str(&format!(
                    "{}!();\n",
                    shared_view_method_macro_name(class.id, target.id)
                ));
                output.push_str("}\n");
                emit_shared_internal_method_impl(&mut output, class.id, target, &stage);
            }
            output.push_str(&format!(
                "impl __rpp_runtime_object_sealed::Sealed for {storage} {{}}\nimpl RustppObject for {storage} {{ fn __rpp_complete_address(&self) -> usize {{ self as *const Self as usize }} fn __rpp_type_desc(&self) -> &'static __RppTypeDesc {{ &{} }} }}\n",
                type_descriptor_name(class.id)
            ));
            for target in class_view_closure(module, class.id) {
                let target_seal = format!("__rpp_{}_sealed", target.name.to_lowercase());
                output.push_str(&format!(
                    "impl {target_seal}::Sealed for {storage} {{}}\nimpl {}View for {storage} {{\n",
                    target.name
                ));
                output.push_str(&format!(
                    "{}!();\n",
                    shared_view_method_macro_name(class.id, target.id)
                ));
                output.push_str("}\n");
                emit_shared_internal_method_impl(&mut output, class.id, target, &storage);
            }
            emit_rooted_ancestor_stages(&mut output, abi_identity, module, class);
            emit_complete_lifecycle(&mut output, module, class);
        }
        output.push_str(&format!("pub type {box_owner} = Box<dyn {view}>;\n"));
        output.push_str(&format!(
            "pub type {rc_owner} = std::rc::Rc<dyn {view}>;\npub type {arc_owner} = std::sync::Arc<dyn {view}>;\n"
        ));
        output.push_str(&format!("pub struct {};\n", class.name));
        if class.abstract_ {
            continue;
        }
        output.push_str(&format!("impl {} {{\n", class.name));
        output.push_str("pub fn construct_box(");
        emit_params(&mut output, module, &class.constructor);
        output.push_str(&format!(
            ") -> {box_owner} {{\nlet (raw_data, frame) = {data}::__rpp_new("
        ));
        emit_arguments(&mut output, &class.constructor);
        output.push_str(");\n");
        output.push_str("let mut data = Box::new(raw_data);\ndata.__rpp_init_complete(frame);\n");
        output.push_str(&format!(
            "// SAFETY [SC-ACTIVATION-COMMIT, SC-DATA-STORAGE-LAYOUT]: `data` is uniquely owned, fully initialized, activated at its final allocation address, and the transparent Storage wrapper has identical layout.\nlet live: Box<{storage}> = unsafe {{ Box::from_raw(Box::into_raw(data).cast::<{storage}>()) }};\nlive\n"
        ));
        output.push_str("}\n");

        output.push_str("pub fn construct_rc(");
        emit_params(&mut output, module, &class.constructor);
        output.push_str(&format!(
            ") -> {rc_owner} {{\nlet (raw_data, frame) = {data}::__rpp_new("
        ));
        emit_arguments(&mut output, &class.constructor);
        output.push_str(");\n");
        output.push_str("let mut data = std::rc::Rc::new(raw_data);\nstd::rc::Rc::get_mut(&mut data).expect(\"construction owner must be unique\").__rpp_init_complete(frame);\n");
        output.push_str(&format!(
            "// SAFETY [SC-ACTIVATION-COMMIT, SC-DATA-STORAGE-LAYOUT]: construction retains the only Rc owner until activation succeeds; the allocation is unchanged and the transparent Storage wrapper has identical layout.\nlet live: std::rc::Rc<{storage}> = unsafe {{ std::rc::Rc::from_raw(std::rc::Rc::into_raw(data).cast::<{storage}>()) }};\nlive\n"
        ));
        output.push_str("}\n");

        output.push_str("pub fn construct_arc(");
        emit_params(&mut output, module, &class.constructor);
        output.push_str(&format!(
            ") -> {arc_owner} {{\nlet (raw_data, frame) = {data}::__rpp_new("
        ));
        emit_arguments(&mut output, &class.constructor);
        output.push_str(");\n");
        output.push_str("let mut data = std::sync::Arc::new(raw_data);\nstd::sync::Arc::get_mut(&mut data).expect(\"construction owner must be unique\").__rpp_init_complete(frame);\n");
        output.push_str(&format!(
            "// SAFETY [SC-ACTIVATION-COMMIT, SC-DATA-STORAGE-LAYOUT]: construction retains the only Arc owner and publishes no Weak reference until activation succeeds; the allocation is unchanged and the transparent Storage wrapper has identical layout.\nlet live: std::sync::Arc<{storage}> = unsafe {{ std::sync::Arc::from_raw(std::sync::Arc::into_raw(data).cast::<{storage}>()) }};\nlive\n"
        ));
        output.push_str("}\n}\n");
    }

    emit_cast_helpers(&mut output, abi_identity, module);

    for item in &module.rust_items {
        output.push_str(&item.source);
        output.push('\n');
    }

    syn::parse_file(&output).map_err(|error| {
        vec![Diagnostic::internal(format!(
            "internal error: generated invalid Rust: {error}"
        ))]
    })?;
    Ok(output)
}

fn validate_backend_plans(module: &Module) -> Result<(), Vec<Diagnostic>> {
    for class in &module.value_classes {
        if class.fields.iter().any(|field| field.id.owner != class.id) {
            return Err(vec![Diagnostic::internal(
                "internal error: value-class field belongs to the wrong semantic owner",
            )]);
        }
    }
    for class in &module.classes {
        if class.fields.iter().any(|field| field.id.owner != class.id) {
            return Err(vec![Diagnostic::internal(
                "internal error: ordinary-class field belongs to the wrong semantic owner",
            )]);
        }
        let activation_ids: Vec<_> = class
            .lifecycle
            .activation
            .iter()
            .map(|step| match step {
                LifecycleStep::ActivateClass(id) => *id,
                LifecycleStep::DeactivateClass(_) => unreachable!(),
            })
            .collect();
        let deactivation_ids: Vec<_> = class
            .lifecycle
            .deactivation
            .iter()
            .map(|step| match step {
                LifecycleStep::DeactivateClass(id) => *id,
                LifecycleStep::ActivateClass(_) => unreachable!(),
            })
            .collect();
        let mut expected_deactivation = activation_ids.clone();
        expected_deactivation.reverse();
        let visibility_is_valid = class.bases.iter().all(|base| {
            matches!(
                base.visibility,
                crate::hir::BaseVisibility::Public
                    | crate::hir::BaseVisibility::Protected
                    | crate::hir::BaseVisibility::Private
            )
        });
        if activation_ids.last() != Some(&class.id)
            || deactivation_ids != expected_deactivation
            || !visibility_is_valid
        {
            return Err(vec![Diagnostic::internal(
                "internal error: unsupported or inconsistent lifecycle plan",
            )]);
        }
    }
    Ok(())
}

fn emit_params(output: &mut String, module: &Module, constructor: &Constructor) {
    for (index, param) in constructor.params.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&format!(
            "{}: {}",
            param.name,
            backend_type(module, &param.ty)
        ));
    }
}

fn backend_type(module: &Module, ty: &TypeRef) -> String {
    let class_name = |id| {
        module
            .classes
            .iter()
            .find(|class| class.id == id)
            .map(|class| class.name.as_str())
            .expect("resolved class ID must exist")
    };
    match ty.kind {
        TypeKind::Value => backend_value_type(module, &ty.source),
        TypeKind::InvalidClassValue(_) => ty.source.clone(),
        TypeKind::ExactClass(id) => format!("__{}Data", class_name(id)),
        TypeKind::ClassOwner { owner, class } => {
            let suffix = match owner {
                OwnerKind::Box => "Box",
                OwnerKind::Rc => "Rc",
                OwnerKind::Arc => "Arc",
            };
            format!("{}{suffix}", class_name(class))
        }
        TypeKind::ClassBorrow { mutable, class } => {
            let mutability = if mutable { "mut " } else { "" };
            format!("&{mutability}dyn {}View", class_name(class))
        }
    }
}

struct BackendTypeLowerer<'a> {
    module: &'a Module,
}

impl BackendTypeLowerer<'_> {
    fn class_name(&self, ty: &syn::Type) -> Option<&str> {
        let syn::Type::Path(path) = ty else {
            return None;
        };
        if path.qself.is_some() || path.path.segments.len() != 1 {
            return None;
        }
        let segment = path.path.segments.first().unwrap();
        if !matches!(segment.arguments, syn::PathArguments::None) {
            return None;
        }
        self.module
            .classes
            .iter()
            .find(|class| segment.ident == class.name.as_str())
            .map(|class| class.name.as_str())
    }
}

impl syn::fold::Fold for BackendTypeLowerer<'_> {
    fn fold_type_reference(&mut self, mut reference: syn::TypeReference) -> syn::TypeReference {
        if let Some(class) = self.class_name(&reference.elem) {
            reference.elem = Box::new(
                syn::parse_str::<syn::Type>(&format!("dyn {class}View"))
                    .expect("generated class-view reference type must parse"),
            );
            reference
        } else {
            syn::fold::fold_type_reference(self, reference)
        }
    }

    fn fold_type_path(&mut self, path: syn::TypePath) -> syn::TypePath {
        if path.qself.is_none()
            && path.path.segments.len() == 1
            && let Some(segment) = path.path.segments.first()
            && matches!(segment.ident.to_string().as_str(), "Box" | "Rc" | "Arc")
            && let syn::PathArguments::AngleBracketed(arguments) = &segment.arguments
            && arguments.args.len() == 1
            && let Some(syn::GenericArgument::Type(inner)) = arguments.args.first()
            && let Some(class) = self.class_name(inner)
        {
            return syn::parse_str::<syn::TypePath>(&format!("{class}{}", segment.ident))
                .expect("generated class owner alias must parse");
        }
        syn::fold::fold_type_path(self, path)
    }
}

fn backend_value_type(module: &Module, source: &str) -> String {
    use quote::ToTokens;
    use syn::fold::Fold;
    let Ok(ty) = syn::parse_str::<syn::Type>(source) else {
        return source.to_owned();
    };
    BackendTypeLowerer { module }
        .fold_type(ty)
        .to_token_stream()
        .to_string()
}

fn backend_method_signature(module: &Module, source: &str) -> String {
    use quote::ToTokens;
    use syn::fold::Fold;

    let signature = syn::parse_str::<syn::Signature>(source)
        .expect("method signatures were validated during HIR lowering");
    BackendTypeLowerer { module }
        .fold_signature(signature)
        .to_token_stream()
        .to_string()
}

fn backend_trait_method_signature(module: &Module, source: &str) -> String {
    use quote::ToTokens;
    use syn::fold::Fold;

    let signature = syn::parse_str::<syn::Signature>(source)
        .expect("method signatures were validated during HIR lowering");
    let mut signature = BackendTypeLowerer { module }.fold_signature(signature);
    for input in &mut signature.inputs {
        if let syn::FnArg::Typed(input) = input
            && let syn::Pat::Ident(pattern) = input.pat.as_mut()
        {
            pattern.by_ref = None;
            pattern.mutability = None;
            pattern.subpat = None;
        }
    }
    signature.to_token_stream().to_string()
}

