fn emit_type_descriptor(
    output: &mut String,
    source_name: &str,
    module: &Module,
    class: &crate::hir::Class,
    storage: &str,
) {
    let targets = class_view_closure(module, class.id);
    for target in &targets {
        let const_thunk = cast_const_thunk_name(class.id, target.id);
        let mut_thunk = cast_mut_thunk_name(class.id, target.id);
        output.push_str(&format!(
            "unsafe fn {const_thunk}(root: *const (), out: *mut ()) {{\n\
             let storage = root.cast::<{storage}>();\n\
             let view: *const dyn {}View = storage;\n\
             // SAFETY [SC-CAST-THUNK]: `out` points to writable storage for exactly one target trait-object pointer and Rust created its metadata.\n\
             unsafe {{ out.cast::<*const dyn {}View>().write(view); }}\n\
             }}\n",
            target.name, target.name
        ));
        output.push_str(&format!(
            "unsafe fn {mut_thunk}(root: *mut (), out: *mut ()) {{\n\
             let storage = root.cast::<{storage}>();\n\
             let view: *mut dyn {}View = storage;\n\
             // SAFETY [SC-CAST-THUNK]: `out` points to writable storage for exactly one target trait-object pointer and the root is uniquely borrowed.\n\
             unsafe {{ out.cast::<*mut dyn {}View>().write(view); }}\n\
             }}\n",
            target.name, target.name
        ));
    }
    let id = stable_class_id(source_name, &class.name);
    output.push_str(&format!(
        "static {}: __RppTypeDesc = __RppTypeDesc {{ active_class: __RppClassId({id}), complete_storage_class: __RppClassId({id}), casts: &[\n",
        type_descriptor_name(class.id)
    ));
    for target in targets {
        output.push_str(&format!(
            "__RppCastEntry {{ target: __RppClassId({}), make_const: {}, make_mut: {} }},\n",
            stable_class_id(source_name, &target.name),
            cast_const_thunk_name(class.id, target.id),
            cast_mut_thunk_name(class.id, target.id)
        ));
    }
    output.push_str("] };\n");
}

fn emit_rooted_ancestor_stages(
    output: &mut String,
    source_name: &str,
    module: &Module,
    complete: &crate::hir::Class,
) {
    let complete_data = format!("__{}Data", complete.name);
    for active in class_view_closure(module, complete.id)
        .into_iter()
        .filter(|active| active.id != complete.id)
    {
        let stage = rooted_stage_name(complete.id, active.id);
        let descriptor = rooted_stage_descriptor_name(complete.id, active.id);
        output.push_str(&format!(
            "#[allow(dead_code)] #[repr(transparent)] struct {stage}({complete_data});\n\
             unsafe fn __rpp_borrow_rooted_stage_{}_{}(data: &mut {complete_data}) -> &mut {stage} {{\n\
             // SAFETY [SC-STAGE-VIEW, SC-DATA-STORAGE-LAYOUT]: transparent rooted-stage layout matches complete Data and the output lifetime is tied to the input borrow.\n\
             unsafe {{ &mut *(data as *mut {complete_data}).cast::<{stage}>() }}\n\
             }}\n\
             impl __rpp_runtime_object_sealed::Sealed for {stage} {{}}\n\
             impl RustppObject for {stage} {{\n\
             fn __rpp_complete_address(&self) -> usize {{ self as *const Self as usize }}\n\
             fn __rpp_type_desc(&self) -> &'static __RppTypeDesc {{ &{descriptor} }}\n\
             }}\n",
            complete.id.0,
            active.id.0
        ));
        let targets = class_view_closure(module, active.id);
        for target in &targets {
            let target_seal = format!("__rpp_{}_sealed", target.name.to_lowercase());
            output.push_str(&format!(
                "impl {target_seal}::Sealed for {stage} {{}}\nimpl {}View for {stage} {{\n",
                target.name
            ));
            for method in target.methods.iter().filter(|method| {
                method.public
                    && (matches!(method.kind, crate::hir::MethodKind::NonVirtual)
                        || method.slot == Some(method.id))
            }) {
                let implementation = method
                    .slot
                    .and_then(|slot| try_resolve_slot_implementation(module, active.id, slot))
                    .or_else(|| method.body.as_ref().map(|_| method));
                if let Some(implementation) = implementation {
                    output.push_str(&backend_method_signature(module, &implementation.signature));
                    output.push_str(" {\n");
                    output.push_str(&rewrite_method_body(module, complete.id, implementation));
                    output.push_str("\n}\n");
                } else {
                    output.push_str(&backend_method_signature(module, &method.signature));
                    output.push_str(
                        " { panic!(\"abstract virtual slot invoked during its lifecycle stage\") }\n",
                    );
                }
            }
            output.push_str("}\n");
            emit_internal_method_impl(output, module, complete.id, active.id, target, &stage);
        }

        for target in &targets {
            let const_thunk = format!(
                "__rpp_stage_cast_{}_{}_{}_const",
                complete.id.0, active.id.0, target.id.0
            );
            let mut_thunk = format!(
                "__rpp_stage_cast_{}_{}_{}_mut",
                complete.id.0, active.id.0, target.id.0
            );
            output.push_str(&format!(
                "unsafe fn {const_thunk}(root: *const (), out: *mut ()) {{\n\
                 let stage = root.cast::<{stage}>();\n\
                 let view: *const dyn {}View = stage;\n\
                 // SAFETY [SC-CAST-THUNK]: `out` points to writable storage for one stage-bounded target trait-object pointer.\n\
                 unsafe {{ out.cast::<*const dyn {}View>().write(view); }}\n\
                 }}\n",
                target.name, target.name
            ));
            output.push_str(&format!(
                "unsafe fn {mut_thunk}(root: *mut (), out: *mut ()) {{\n\
                 let stage = root.cast::<{stage}>();\n\
                 let view: *mut dyn {}View = stage;\n\
                 // SAFETY [SC-CAST-THUNK]: `out` points to writable storage for one uniquely borrowed stage-bounded target pointer.\n\
                 unsafe {{ out.cast::<*mut dyn {}View>().write(view); }}\n\
                 }}\n",
                target.name, target.name
            ));
        }
        output.push_str(&format!(
            "static {descriptor}: __RppTypeDesc = __RppTypeDesc {{ active_class: __RppClassId({}), complete_storage_class: __RppClassId({}), casts: &[\n",
            stable_class_id(source_name, &active.name),
            stable_class_id(source_name, &complete.name)
        ));
        for target in targets {
            output.push_str(&format!(
                "__RppCastEntry {{ target: __RppClassId({}), make_const: __rpp_stage_cast_{}_{}_{}_const, make_mut: __rpp_stage_cast_{}_{}_{}_mut }},\n",
                stable_class_id(source_name, &target.name),
                complete.id.0,
                active.id.0,
                target.id.0,
                complete.id.0,
                active.id.0,
                target.id.0
            ));
        }
        output.push_str("] };\n");
    }
}

