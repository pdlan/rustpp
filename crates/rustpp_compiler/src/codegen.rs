fn class_view_closure(module: &Module, root: crate::hir::ClassId) -> Vec<&crate::hir::Class> {
    fn visit<'a>(
        module: &'a Module,
        id: crate::hir::ClassId,
        seen: &mut std::collections::HashSet<crate::hir::ClassId>,
        output: &mut Vec<&'a crate::hir::Class>,
    ) {
        if !seen.insert(id) {
            return;
        }
        let class = class_by_id(module, id);
        for base in &class.bases {
            visit(module, base.class, seen, output);
        }
        output.push(class);
    }

    let mut seen = std::collections::HashSet::new();
    let mut output = Vec::new();
    visit(module, root, &mut seen, &mut output);
    output
}

