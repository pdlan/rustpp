fn rewrite_rooted_lifecycle_body(
    module: &Module,
    complete: crate::hir::ClassId,
    class: &crate::hir::Class,
    body: &str,
) -> String {
    use quote::ToTokens;
    use syn::fold::Fold;

    struct LifecycleRewriter {
        projections: std::collections::HashMap<String, String>,
    }

    impl Fold for LifecycleRewriter {
        fn fold_macro(&mut self, mut item: syn::Macro) -> syn::Macro {
            item.tokens = rewrite_lifecycle_macro_tokens(item.tokens, &self.projections);
            item
        }

        fn fold_expr_path(&mut self, path: syn::ExprPath) -> syn::ExprPath {
            if path.path.to_token_stream().to_string() == "self" {
                syn::parse_quote!(stage)
            } else {
                path
            }
        }

        fn fold_expr(&mut self, expression: syn::Expr) -> syn::Expr {
            if let syn::Expr::Field(field) = &expression
                && let syn::Member::Named(member) = &field.member
                && let syn::Expr::Path(base) = field.base.as_ref()
                && base.path.to_token_stream().to_string() == "self"
                && let Some(projection) = self.projections.get(&member.to_string())
            {
                return syn::parse_str::<syn::Expr>(&format!("{projection}.{member}"))
                    .expect("generated lifecycle field projection must parse");
            }
            if let syn::Expr::Path(path) = &expression
                && path.path.to_token_stream().to_string() == "self"
            {
                return syn::parse_quote!(stage);
            }
            syn::fold::fold_expr(self, expression)
        }
    }

    let mut projections = std::collections::HashMap::new();
    for visible in class_view_closure(module, class.id) {
        let mut base = String::from("stage.0");
        for step in projection_path(module, complete, visible.id)
            .expect("unique lifecycle field projection must exist")
        {
            base.push('.');
            base.push_str(&base_data_field(step));
        }
        for field in visible
            .fields
            .iter()
            .filter(|field| visible.id == class.id || field.public)
        {
            projections
                .entry(field.name.clone())
                .or_insert(base.clone());
        }
    }
    let block = syn::parse_str::<syn::Block>(&format!("{{{body}}}"))
        .expect("lifecycle bodies must be valid Rust-compatible blocks");
    let rewritten = LifecycleRewriter { projections }.fold_block(block);
    rewritten
        .stmts
        .iter()
        .map(ToTokens::to_token_stream)
        .map(|tokens| tokens.to_string())
        .collect::<Vec<_>>()
        .join(" ")
}

fn rewrite_lifecycle_macro_tokens(
    tokens: proc_macro2::TokenStream,
    projections: &std::collections::HashMap<String, String>,
) -> proc_macro2::TokenStream {
    use proc_macro2::{Group, Ident, TokenStream, TokenTree};
    let input: Vec<_> = tokens.into_iter().collect();
    let mut output = TokenStream::new();
    let mut index = 0usize;
    while index < input.len() {
        match &input[index] {
            TokenTree::Group(group) => {
                let mut rewritten = Group::new(
                    group.delimiter(),
                    rewrite_lifecycle_macro_tokens(group.stream(), projections),
                );
                rewritten.set_span(group.span());
                output.extend([TokenTree::Group(rewritten)]);
                index += 1;
            }
            TokenTree::Ident(ident) if ident == "self" => {
                let field_name = match (input.get(index + 1), input.get(index + 2)) {
                    (Some(TokenTree::Punct(dot)), Some(TokenTree::Ident(field)))
                        if dot.as_char() == '.' =>
                    {
                        Some(field.to_string())
                    }
                    _ => None,
                };
                if let Some(projection) =
                    field_name.as_ref().and_then(|field| projections.get(field))
                {
                    let replacement: TokenStream =
                        format!("{projection}.{}", field_name.as_deref().unwrap())
                            .parse()
                            .expect("generated macro field projection must tokenize");
                    output.extend(replacement);
                    index += 3;
                } else {
                    output.extend([TokenTree::Ident(Ident::new("stage", ident.span()))]);
                    index += 1;
                }
            }
            token => {
                output.extend([token.clone()]);
                index += 1;
            }
        }
    }
    output
}

